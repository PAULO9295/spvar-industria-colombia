def create_propagation_png(gdf_map, w_ui, betas_dict, rho_fallback, dept_name, mode, dgini, dedu, dpib_pct, rho_override=None):
    # Lógica de mapa de propagación simplificada (basada en tu Celda 15B)
    idx = gdf_map[gdf_map[NOMBRE_COL] == dept_name].index[0]
    rho_eff = float(np.clip(rho_override if rho_override is not None else rho_fallback, -0.9, 0.9))
    A = rho_eff * w_ui.full()[0]
    try: S = np.linalg.inv(np.eye(len(gdf_map)) - A)
    except: S = np.eye(len(gdf_map))

    deltas = {"gini": dgini, "educacion_superior": dedu, "log_pib_percapita": dpib_pct}
    impacts = {}
    for var in deltas:
        shock = np.zeros(len(gdf_map)); shock[idx] = betas_dict.get(var, 0.0) * deltas[var]
        impacts[var] = (S @ shock) * 100
    impacts["combined"] = sum(impacts.values())

    impact_pct = impacts[mode]
    gdf_plot = gdf_map.to_crs(epsg=4326).copy()
    gdf_plot["impact"] = impact_pct
    abs_imp = np.abs(impact_pct); max_abs = float(abs_imp.max()) if abs_imp.max() > 1e-6 else 1e-6
    top_idx = [i for i in np.argsort(abs_imp)[::-1] if i != idx and abs_imp[i] > max_abs * 0.02][:14]
    centroids = np.array([[p.x, p.y] for p in gdf_plot.geometry.centroid])
    ox, oy = centroids[idx]

    fig, ax = plt.subplots(figsize=(10, 8), dpi=110)
    gdf_plot.plot(column="impact", ax=ax, cmap="RdBu_r", vmin=-max_abs, vmax=max_abs, edgecolor="#0d0d0d", linewidth=1.0, legend=True, legend_kwds={"shrink": 0.6})

    for dest in top_idx:
        dx, dy = centroids[dest]
        color = "#d92d2d" if impact_pct[dest] > 0 else "#3360dc"
        ax.add_patch(FancyArrowPatch((ox, oy), (dx, dy), arrowstyle="-|>", mutation_scale=12, color=color, alpha=0.75, linewidth=1.5, connectionstyle="arc3,rad=0.1", shrinkA=10, shrinkB=10))

    ax.add_patch(Circle((ox, oy), 0.8, color="gold", alpha=0.3))
    ax.plot(ox, oy, marker="*", markersize=20, color="#FFD700", markeredgecolor="#111")
    ax.set_title(f"Propagación: {mode} | Origen: {dept_name} | ρ={rho_eff:.2f}", fontsize=10, fontweight="bold")
    ax.set_xlim(-80, -66); ax.set_ylim(-5, 14); ax.axis("off")

    buf = _Bio()
    fig.savefig(buf, format="png", bbox_inches="tight", pad_inches=0.1)
    plt.close(fig)
    return buf.getvalue()

def plot_simulacion(gdf_map, w_ui, betas_dict, rho_fallback, dept_name, dgini, dedu, dpib_pct, rho_override):
    # Lógica simplificada para gráficos de barras e IRF
    idx = gdf_map[gdf_map[NOMBRE_COL] == dept_name].index[0]
    rho_eff = float(np.clip(rho_override, -0.9, 0.9))
    A = rho_eff * w_ui.full()[0]
    try: S = np.linalg.inv(np.eye(len(gdf_map)) - A)
    except: S = np.eye(len(gdf_map))

    shock = np.zeros(len(gdf_map))
    shock[idx] = betas_dict.get("gini", 0) * dgini + betas_dict.get("educacion_superior", 0) * dedu + betas_dict.get("log_pib_percapita", 0) * dpib_pct
    total_impact = (S @ shock) * 100

    fig_bar = go.Figure(go.Bar(x=gdf_map[NOMBRE_COL], y=total_impact, marker_color=["#c0392b" if i == idx else "#2980b9" for i in range(len(gdf_map))]))
    fig_bar.update_layout(title="Impacto total por Departamento", yaxis_title="Δ log(Industria) [%]", height=400)

    cur = shock.copy(); irf = []
    for _ in range(12):
        irf.append(cur[idx] * 100); cur = A @ cur
    fig_irf = go.Figure(go.Scatter(y=irf, mode="lines+markers"))
    fig_irf.update_layout(title="IRF Espacial", xaxis_title="Orden de vecinos", yaxis_title="Δ log(Industria) [%]", height=400)

    return fig_bar, fig_irf

